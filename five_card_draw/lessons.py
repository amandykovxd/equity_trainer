def lesson_rules() -> None:
    ui.title("Урок 1. Самые простые правила в покере")
    ui.para("""
        Пятикарточный дро — та игра, в которую обычно играют дома.
        Если вы начинаете с нуля, с неё удобно начинать: правил
        минимум, общих карт нет, думать про борд не нужно.
    """)

    ui.section("Как идёт раздача")
    ui.block("""
        1. Каждому сдают 5 закрытых карт.
        2. Круг ставок.
        3. Замена: можно сбросить любое число своих карт и получить
           столько же новых. Можно не менять ничего — это называется
           «пэт».
        4. Ещё круг ставок.
        5. Вскрытие: банк забирает сильнейшая комбинация.
    """)
    print()
    ui.para("""
        Комбинации обычные, как в холдеме: от старшей карты
        до флеш-рояля. Всё, что нужно знать про силу рук, вы уже
        знаете.
    """)

    ui.section("Что здесь особенного")
    ui.para("""
        Общих карт нет, поэтому про соперника известно почти ничего.
        Единственная информация — сколько карт он поменял:

          поменял 3 карты  →  скорее всего держал пару;
          поменял 2        →  возможно, тройку или две карты до флеша;
          поменял 1        →  похоже на дро к стриту или флешу,
                              либо две пары;
          не менял вовсе   →  заявляет готовую руку.

        Эта информация односторонняя: соперник тоже видит, сколько
        карт поменяли вы.
    """)
    ui.hint("Отсюда главный приём игры: иногда стоит менять не то "
            "число карт, которое выгодно по комбинации, а то, которое "
            "вводит соперника в заблуждение.")


def lesson_drawing() -> None:
    ui.title("Урок 2. Сколько карт менять")
    ui.para("""
        Это главное решение в дро-покере. Посчитаем варианты
        на настоящих числах — прямо сейчас, а не по учебнику.
    """)

    ui.section("У вас пара девяток, у соперника пара дам")
    ui.para("""
        Соперник карты не меняет. Вы проигрываете прямо сейчас,
        значит нужно улучшиться. Вопрос: оставить только пару
        и взять три карты — или придержать ещё и старший кикер?
    """)
    villain = parse_cards("QsQd7c4h2s")
    options = [
        ("9s9h", "оставляем только пару, меняем три карты"),
        ("9s9hAd", "оставляем пару и туза, меняем две"),
        ("9s9hAdKc", "оставляем пару, туза и короля, меняем одну"),
    ]
    print()
    print("  Соперник: %s (пара дам, карты не меняет)" % pretty(villain))
    print()
    for hand_text, comment in options:
        hero = parse_cards(hand_text)
        result = equity(VARIANT, [hero, villain], iterations=12000, seed=2)
        print("  %s  меняем %d → equity %5.1f%%  %s"
              % (ui.pad(pretty(hero), 18), VARIANT.hole_size - len(hero),
                 result.hero_equity * 100, ui.bar(result.hero_equity, 18)))
        ui.para(comment, indent=6)
    print()
    ui.para("""
        Чем больше карт вы меняете, тем выше equity. Соблазн придержать
        «хорошего кикера» — типичная ошибка новичка: кикер почти ничего
        не добавляет, зато вы теряете шанс улучшиться.
    """)
    ui.hint("Правило простое: с парой меняют три карты. Кикер имеет "
            "значение только когда у обоих одинаковая комбинация, "
            "а это куда реже, чем шанс собрать вторую пару.")

    ui.section("Во что превращается пара при размене трёх карт")
    import random

    from core.cards import full_deck
    from core.evaluator import CATEGORY_NAMES_RU
    from core.evaluator import evaluate as evaluate_hand

    keep = parse_cards("9s9h")
    deck = [card for card in full_deck() if card not in set(keep)]
    rng = random.Random(1)
    rounds = 40_000
    counts = {}
    for _ in range(rounds):
        category = evaluate_hand(keep + rng.sample(deck, 3))[0]
        counts[category] = counts.get(category, 0) + 1
    print()
    for category in sorted(counts, reverse=True):
        share = counts[category] / rounds
        print("  %s %6.2f%%  %s" % (ui.pad(CATEGORY_NAMES_RU[category], 16),
                                    share * 100, ui.bar(share, 18)))
    print()
    ui.para("""
        То есть примерно в семи случаях из десяти у вас по-прежнему
        просто пара. Это нормально: пара часто и выигрывает, потому что
        у соперника тоже обычно ничего. Но рассчитывать на тройку
        не стоит — она приходит примерно раз в десять разменов.
    """)


def lesson_strategy() -> None:
    ui.title("Урок 3. Базовая стратегия")
    ui.para("""
        В дро-покере мало информации, поэтому стратегия строится
        на простых правилах, а не на расчётах.
    """)

    ui.section("С чем входить в раздачу")
    ui.block("""
        Играем:     пара валетов и выше;
                    любые две пары, тройка и лучше;
                    четыре карты до флеша или до стрита.
        Сбрасываем: мелкие пары с ранней позиции;
                    четыре карты до стрита с дыркой внутри;
                    всё остальное.
    """)
    print()

    ui.section("Позиция важна и здесь")
    ui.para("""
        Тот, кто говорит последним, видит, сколько карт поменяли
        остальные, прежде чем принять решение. Это ровно та же
        ценность позиции, что и в холдеме.
    """)

    ui.section("Блеф в дро-покере")
    ui.para("""
        Поскольку соперник не видит ваших карт вообще, блеф здесь
        работает прямолинейно: не меняя карт («пэт») и уверенно ставя,
        вы заявляете готовую сильную руку. Проверить это соперник может
        только деньгами.

        Обратная сторона: тот же приём против вас стоит столько же.
        Поэтому не стоит автоматически верить тому, кто не менял карт.
    """)
    ui.hint("Для новичка самое выгодное в дро-покере — играть мало рук "
            "и внимательно смотреть, сколько карт меняют соперники. "
            "Этой информации больше, чем кажется.")


