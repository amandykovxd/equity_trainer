def lesson_equity() -> None:
    ui.title("Урок 3. Equity — главное число в покере")
    ui.para("""
        Equity — это доля банка, которая «ваша по справедливости».
        Если ваша equity 70%, то при многократном повторении этой
        ситуации вы забирали бы 70% банка.

        Почему это важно: в покере нельзя выиграть каждую раздачу,
        но можно каждый раз принимать решение, которое в среднем
        приносит деньги. Equity — это то, с чем вы сравниваете цену
        своего решения.
    """)

    ui.section("Сильная рука ≠ гарантия")
    cases = [
        ("AsAh", "KsKd", 1, "Лучшая рука против второй по силе"),
        ("AhKh", "2c2d", 1, "Туз-король против младшей пары — почти монетка"),
        ("AsAh", None, 1, "Тузы против одного случайного соперника"),
        ("AsAh", None, 8, "Тузы против восьми случайных соперников"),
    ]
    print()
    for hero_text, villain_text, opponents, comment in cases:
        hero = parse_cards(hero_text)
        if villain_text:
            result = equity(hero, [parse_cards(villain_text)], seed=7)
            against = pretty(parse_cards(villain_text))
        elif opponents == 1:
            result = equity_vs_random(hero, 1, seed=7)
            against = "случайной руки"
        else:
            result = equity_vs_random(hero, opponents, seed=7)
            against = "%d случайных рук" % opponents
        print("  %s  против %s %5.1f%%  %s"
              % (pretty(hero), ui.pad(against, 18), result.hero_equity * 100,
                 ui.bar(result.hero_equity, 20)))
        ui.para(comment, indent=6)
    print()
    ui.hint("Тузы — лучшая рука, но против восьми соперников они выигрывают "
            "меньше половины раздач. Чем больше игроков в раздаче, тем "
            "меньше ваша equity — и тем осторожнее нужно играть.")

    ui.section("Самое важное следствие")
    ui.para("""
        Проиграть с хорошей рукой — нормально. Это не ошибка, а часть игры.
        Ошибка — это принять решение, у которого не было математических
        оснований. Именно их мы и учимся считать в следующих уроках.
    """)


def lesson_outs() -> None:
    ui.title("Урок 4. Аутсы и правило 2 и 4")
    ui.para("""
        Аут — карта, которая делает вашу руку выигрышной. Считать аутсы
        нужно уметь в голове: это основа всех решений на флопе и тёрне.
    """)

    hero = parse_cards("9h8h")
    villain = parse_cards("KsQd")
    board = parse_cards("Kh7h2c")

    ui.section("Разберём конкретную ситуацию")
    print("  Ваши карты:      %s" % pretty(hero))
    print("  Борд (флоп):     %s" % pretty(board))
    print("  У соперника:     %s  (%s)" % (pretty(villain), describe(villain + board)))
    print()
    ui.para("""
        Прямо сейчас у вас %s — вы проигрываете. Но у вас четыре червы:
        любая пятая черва даст флеш, который побьёт пару королей.
        Такая незавершённая рука называется «дро».
    """ % describe(hero + board).lower())

    outs, ties = outs_vs_villain(hero, villain, board)
    print()
    print("  Аутсов: %d" % len(outs))
    print("  Это карты: %s" % pretty(sorted(outs, key=lambda c: (-c.rank, c.suit))))
    if ties:
        print("  Плюс %d карт(ы) на ничью: %s" % (len(ties), pretty(ties)))

    ui.section("Правило 2 и 4")
    ui.para("""
        Точную вероятность в уме за столом никто не считает.
        Вместо этого используют правило:
    """)
    print()
    ui.block("""
        осталась 1 карта (тёрн → ривер):  аутсы × 2 = проценты
        осталось 2 карты (флоп → ривер):  аутсы × 4 = проценты
    """, indent=6)
    unseen_from_flop = 47  # 52 − 2 своих − 3 на борде
    print()
    print("  Правило 4 (флоп→ривер): %d × 4 = %.0f%%"
          % (len(outs), rule_of_2_and_4(len(outs), 2) * 100))
    print("  Точная вероятность:     %.1f%%"
          % (exact_improve_chance(len(outs), unseen_from_flop, 2) * 100))
    result = equity(hero, [villain], board, seed=11)
    print("  Реальная equity:        %.1f%%" % (result.hero_equity * 100))
    print()
    ui.para("""
        Три числа близки, но не равны. Правило 2 и 4 — быстрая оценка.
        Точная вероятность считает только попадание в аут. А equity
        учитывает всё: что соперник тоже может улучшиться, что ваша
        рука иногда выигрывает другим способом.
    """)
    ui.hint("Для стола достаточно правила 2 и 4. Этот скрипт нужен, чтобы "
            "вы видели, насколько оно точно — и где начинает врать.")

    ui.section("Сколько аутсов у типичных дро")
    ui.block("""
        Флеш-дро (4 карты одной масти)        — 9 аутсов, ~36% на флопе
        Открытый стрит-дро (например 9-8-7-6) — 8 аутсов, ~32% на флопе
        Гатшот (дырка внутри: 9-8-_-6-5)      — 4 аута,  ~17% на флопе
        Одна карта до старшей пары            — 3 аута,  ~13% на флопе
    """)


def lesson_pot_odds() -> None:
    ui.title("Урок 5. Пот-оддсы: математика одного колла")
    ui.para("""
        Теперь соединим два числа — сколько стоит колл и какая у вас equity.
        Это и есть момент, когда покер перестаёт быть угадыванием.
    """)

    pot, call = 100.0, 50.0
    need = required_equity(pot, call)

    ui.section("Вопрос")
    ui.para("""
        В банке %.0f. Соперник поставил %.0f. Чтобы продолжить, вам нужно
        уравнять %.0f.
    """ % (pot, call, call))

    ui.section("Считаем цену")
    ui.para("""
        Вы вкладываете %.0f, а играете за банк %.0f + %.0f = %.0f.
        Значит, колл окупается, если вы выигрываете чаще, чем
    """ % (call, pot, call, pot + call))
    print()
    ui.block("%.0f / %.0f = %.1f%%" % (call, pot + call, need * 100), indent=6)
    print()
    ui.para("""
        Это и называется пот-оддсы: минимальная equity, при которой
        колл не теряет деньги.
    """)

    hero = parse_cards("9h8h")
    villain = parse_cards("KsQd")
    board = parse_cards("Kh7h2c")
    result = equity(hero, [villain], board, seed=11)

    ui.section("Сравниваем со своей equity")
    print("  Ваши карты: %s    Борд: %s" % (pretty(hero), pretty(board)))
    print("  Нужно equity: %.1f%%" % (need * 100))
    print("  Есть equity:  %.1f%%  %s" % (result.hero_equity * 100,
                                          ui.bar(result.hero_equity, 22)))
    print()
    expected_value = result.hero_equity * (pot + call) - call
    if result.hero_equity > need:
        ui.good("Колл выгоден: equity больше требуемой.")
    else:
        ui.bad("Колл убыточен: equity меньше требуемой — фолд.")
    ui.para("""
        В деньгах: %.1f%% × %.0f − %.0f = %+.1f за каждый такой колл.
        Одна раздача ничего не доказывает, но из тысячи таких решений
        и складывается результат.
    """ % (result.hero_equity * 100, pot + call, call, expected_value))

    ui.section("Шпаргалка: какую equity требует ставка")
    ui.block("""
        Соперник ставит 1/4 банка  → нужно 20%
        Соперник ставит 1/2 банка  → нужно 25%
        Соперник ставит 3/4 банка  → нужно 30%
        Соперник ставит банк       → нужно 33%
        Соперник ставит 2 банка    → нужно 40%
    """)
    ui.hint("Чем больше ставка соперника, тем сильнее должна быть ваша рука. "
            "Это единственная причина, по которой размер ставки вообще важен.")


