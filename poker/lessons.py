def print_chart() -> None:
    """Печатает таблицу 13×13 всех стартовых рук с раскраской по группам."""
    colors = {
        ranges.TIER_PREMIUM: ui.BOLD + ui.GREEN,
        ranges.TIER_STRONG: ui.GREEN,
        ranges.TIER_PLAYABLE: ui.YELLOW,
        ranges.TIER_FOLD: ui.DIM,
    }
    print()
    for row in ranges.chart_rows():
        cells = [ui.color("%-4s" % notation, colors[tier]) for notation, tier in row]
        print("  " + "".join(cells))
    print()
    legend = "   ".join(
        ui.color(ranges.TIER_NAMES[tier], colors[tier])
        for tier in (ranges.TIER_PREMIUM, ranges.TIER_STRONG,
                     ranges.TIER_PLAYABLE, ranges.TIER_FOLD)
    )
    print("  " + legend)
    ui.para("""
        По диагонали — пары, выше диагонали — одномастные руки,
        ниже — разномастные.
    """)


