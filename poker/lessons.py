def lesson_rules() -> None:
    ui.title("Урок 1. Как вообще идёт раздача")
    ui.para("""
        Речь про техасский холдем без лимита — это то, во что играют
        почти везде, от домашних игр до World Series of Poker.
    """)

    ui.section("Что у вас на руках")
    ui.para("""
        Каждому игроку сдают 2 закрытые карты — их видите только вы.
        В центр стола постепенно выкладывают 5 общих карт («борд»),
        их видят все.

        Ваша комбинация — лучшие 5 карт из 7 доступных (2 ваши + 5 общих).
        Можно использовать обе свои карты, одну или даже ни одной.
    """)

    ui.section("Четыре круга ставок")
    ui.block("""
        Префлоп — общих карт нет, вы видите только свои 2 карты.
        Флоп    — открывают сразу 3 общие карты.
        Тёрн    — открывают 4-ю карту.
        Ривер   — открывают 5-ю, последнюю карту.
    """)
    ui.para("""
        После каждого открытия идёт круг ставок. Если после ривера
        осталось больше одного игрока — вскрытие («шоудаун»),
        банк забирает сильнейшая комбинация.
    """)

    ui.section("Что можно делать в свой ход")
    ui.block("""
        Фолд  — сбросить карты и выйти из раздачи. Вы ничего не теряете
                кроме уже поставленного. Это самое частое действие
                у хорошего игрока.
        Чек   — пропустить ход, ничего не ставя. Доступен, когда до вас
                никто не поставил.
        Колл  — уравнять чужую ставку.
        Бет   — поставить первым.
        Рейз  — повысить чужую ставку.
    """)

    ui.section("Блайнды")
    ui.para("""
        Чтобы в банке всегда было за что бороться, два игрока слева от
        дилера обязаны поставить блайнды — малый и большой. Позиция
        дилера сдвигается на одного игрока каждую раздачу, так что
        блайнды платят все по очереди.
    """)

    ui.section("Позиция — то, что новички недооценивают")
    ui.para("""
        Чем позже вы говорите в круге ставок, тем больше информации вы
        уже получили от соперников. Позднее место (на дилере) стоит
        дороже хорошей руки: с него можно играть больше рук и дешевле
        выяснять, что у соперника.
    """)
    ui.hint("Главный вывод урока: покер — это игра не карт, а решений "
            "при неполной информации.")


