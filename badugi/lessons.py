from badugi.rules import VARIANT


def lesson_rules() -> None:
    ui.title("Урок 1. Правила бадуги")
    ui.para("""
        Бадуги — самая необычная из распространённых разновидностей,
        но правил в ней меньше, чем в холдеме. Карт у каждого четыре,
        общих карт нет, есть круги замены.
    """)

    ui.section("Что считается рукой")
    ui.para("""
        Нужна рука, в которой все карты РАЗНЫХ мастей и РАЗНЫХ
        достоинств. Такая рука из четырёх карт и называется «бадуги».
        Чем младше карты, тем лучше; туз — младшая карта.

        Если полного набора нет, рука считается только по трём
        подходящим картам — это называется «снаут». Любое бадуги
        бьёт любой снаут, каким бы низким тот ни был.
    """)

    ui.section("Примеры")
    hands = [
        ("4s3h2dAc", "лучшая возможная рука: четыре масти, четыре "
                     "младших номинала"),
        ("7s5h3d2c", "нормальное рабочее бадуги («семёрка»)"),
        ("Ks9h5d2c", "бадуги, но высокое — скорее проигрыш"),
        ("4s3h2d2c", "две двойки: одна не работает, остаётся снаут 4-3-2"),
        ("4s3h2dAs", "две пики: одна не работает, остаётся снаут 3-2-A"),
        ("4s4h4d4c", "четыре четвёрки — работает только одна карта"),
    ]
    print()
    for hand_text, comment in hands:
        hand = parse_cards(hand_text)
        print("  %s  %s" % (ui.pad(pretty(hand), 18), describe_badugi(hand)))
        ui.para(comment, indent=6)
    print()
    ui.hint("Считайте так: сначала выбросьте мысленно дубликаты "
            "по мастям и по номиналам, а потом смотрите, сколько "
            "карт осталось.")


def lesson_comparing() -> None:
    ui.title("Урок 2. Как сравнивают руки")
    ui.para("""
        Порядок сравнения всего из двух шагов.
    """)
    ui.block("""
        1. Сначала сравнивают число работающих карт:
           бадуги (4) > снаут (3) > две карты > одна карта.
        2. Если число одинаковое, сравнивают сами карты, начиная
           со старшей. Младше — значит лучше.
    """)
    print()

    ui.section("Пример на каждый шаг")
    pairs = [
        ("Ks Qh Jd Tc", "7s5h3d3c",
         "высокое бадуги против низкого снаута — бадуги сильнее"),
        ("7s5h3d2c", "7d6s3c2h",
         "оба бадуги, старшая семёрка у обоих; дальше 5 против 6"),
        ("As2h3d4c", "4s3h2dAc",
         "одни и те же номиналы — руки равны, банк делится"),
    ]
    print()
    for first_text, second_text, comment in pairs:
        first, second = parse_cards(first_text), parse_cards(second_text)
        result = equity(VARIANT, [first, second], seed=3)
        print("  %s  против  %s" % (ui.pad(pretty(first), 18),
                                    pretty(second)))
        print("      %s" % describe_badugi(first))
        print("      %s" % describe_badugi(second))
        print("      доля первого игрока в банке: %.0f%%"
              % (result.hero_equity * 100))
        ui.para(comment, indent=6)
        print()


def lesson_strategy() -> None:
    ui.title("Урок 3. Замена и базовая стратегия")
    ui.para("""
        В бадуги обычно три круга замены, как в трипл-дро. Решение
        каждый раз одно: сколько карт менять.
    """)

    ui.section("Что меняют")
    ui.block("""
        Готовое низкое бадуги (7 или лучше)  не меняем — «стоим пэт»
        Снаут из трёх низких карт            меняем одну
        Две низкие карты разных мастей       меняем две
        Остальное                            обычно сбрасываем
    """)
    print()
    ui.para("""
        Снаут из трёх младших карт — самая частая рабочая ситуация:
        вы меняете одну карту и надеетесь получить такую, которая
        не совпадёт ни по масти, ни по номиналу с уже имеющимися.
    """)

    ui.section("Насколько велик шанс добрать бадуги")
    ui.para("""
        Посчитаем прямо: у вас снаут из трёх карт, вы меняете одну.
        Нужна карта четвёртой масти и нового достоинства.
    """)
    hero = parse_cards("5s3h2d")
    villain = parse_cards("7s6h4d3c")
    result = equity(VARIANT, [hero, villain], iterations=12000, seed=4)
    print()
    print("  У вас снаут:      %s  (меняете одну карту)" % pretty(hero))
    print("  У соперника:      %s  (%s)"
          % (pretty(villain), describe_badugi(villain)))
    print("  Ваша equity:      %.1f%%  %s"
          % (result.hero_equity * 100, ui.bar(result.hero_equity, 20)))
    print()
    ui.para("""
        Нужна карта четвёртой масти, то есть одна из тринадцати,
        и при этом нового достоинства — три номинала уже заняты.
        Подходящих карт остаётся около десяти из сорока пяти,
        которых вы не видите: примерно каждая пятая.

        Но equity всего около 9%, и вот почему: у соперника бадуги
        уже собрано. Вам недостаточно просто добрать — нужно добрать
        НИЖЕ его руки. Из десяти подходящих карт это делают только
        четыре: туз, четвёрка, шестёрка и семёрка.

        Отсюда главный вывод: против заявленного пэта снаут почти
        не играет. Снаутом хорошо идти против того, кто тоже меняет
        карты.
    """)
    ui.hint("Бадуги прощает меньше других игр: собранная рука здесь "
            "почти всегда держится до конца, потому что улучшаться "
            "соперникам тоже тяжело. Поэтому пэт с низким бадуги "
            "играют агрессивно.")


