"""Уроки разза."""
from __future__ import annotations

from typing import Callable, List, Tuple

from core import ui
from core.cards import parse_cards, pretty
from core.equity import equity
from core.lowball import describe_ace_to_five
from razz.rules import VARIANT


def lesson_rules() -> None:
    ui.title("Урок 1. Покер наоборот: побеждает слабейшая рука")
    ui.para("""
        Разз устроен как семикарточный стад — те же пять улиц, те же
        семь карт, те же четыре открытые карты. Отличие одно, но оно
        переворачивает всё: банк забирает самая СЛАБАЯ рука.
    """)

    ui.section("Три правила системы A-5")
    ui.block("""
        1. Туз — младшая карта. Он считается за единицу.
        2. Стриты и флеши не считаются вообще. Они не портят руку
           и не улучшают её — масти и порядок просто игнорируются.
        3. Пары, тройки и каре — плохо. Любая рука без пар лучше
           любой руки с парой.
    """)
    print()
    ui.para("""
        Отсюда лучшая возможная рука: 5-4-3-2-A. Её называют «колесо».
        Обыграть её нельзя, можно только разделить банк с таким же
        колесом.
    """)

    ui.section("Как читают лоу-руки")
    hands = [
        ("5s4h3d2cAs", "колесо — лучшая рука в раззе"),
        ("6s4h3d2cAs", "«шестёрка-четыре» — вторая по силе"),
        ("8s7h5d3cAs", "«восьмёрка-семь» — средняя рука"),
        ("8s6h5d3cAs", "«восьмёрка-шесть» — лучше предыдущей"),
        ("Ks9h7d4c2s", "«король» — почти наверняка проигрыш"),
        ("AsAh5d4c3s", "пара тузов — хуже любой руки без пар"),
    ]
    print()
    for hand_text, comment in hands:
        hand = parse_cards(hand_text)
        print("  %s  %s" % (ui.pad(pretty(hand), 20),
                            describe_ace_to_five(hand)))
        ui.para(comment, indent=6)
    print()
    ui.para("""
        Руку называют по двум старшим картам. Сравнивают тоже
        со старших: у «восьмёрки-семь» и «восьмёрки-шесть» первая карта
        одинаковая, а вторая решает дело — шестёрка младше семёрки,
        значит эта рука лучше.
    """)
    ui.hint("Самое трудное для новичка — переучить рефлекс. Пара тузов "
            "здесь не «сильная рука», а катастрофа: она хуже, чем "
            "король-девятка без пары.")


def lesson_reading() -> None:
    ui.title("Урок 2. Считаем, кто впереди")
    ui.para("""
        В раззе, как и везде, бывает «впереди по руке» и «впереди
        по equity» — и это не одно и то же, потому что карт впереди
        ещё много.
    """)

    hero = parse_cards("As2d3h")
    villain = parse_cards("5s6d7h")
    ui.section("Три карты против трёх")
    print("  У вас:      %s" % pretty(hero))
    print("  У соперника:%s" % pretty(villain))
    print()
    result = equity(VARIANT, [hero, villain], iterations=8000, seed=4)
    print("  Ваша equity: %.1f%%  %s"
          % (result.hero_equity * 100, ui.bar(result.hero_equity, 22)))
    ui.para("""
        Обе руки — три низкие карты без пар, то есть обе хороши.
        A-2-3 впереди, но перевес небольшой: впереди ещё четыре карты,
        и они решают куда больше, чем стартовое преимущество. Запас
        прочности у младших карт всё же есть — именно он и даёт
        эти несколько процентов.
    """, indent=4)

    ui.section("Что портит руку")
    cases = [
        ("As2d3h", "Три младшие карты — идеальный старт"),
        ("As2d8h", "Две младшие и восьмёрка — уже хуже"),
        ("As2dKh", "Король в руке почти наверняка придётся выбросить"),
        ("AsAd2h", "Пара тузов — старт, который надо сбрасывать"),
    ]
    print()
    print("  Против одной и той же руки соперника: %s" % pretty(villain))
    print()
    for hand_text, comment in cases:
        hand = parse_cards(hand_text)
        result = equity(VARIANT, [hand, villain], iterations=6000, seed=8)
        print("  %s  %5.1f%%  %s"
              % (ui.pad(pretty(hand), 14), result.hero_equity * 100,
                 ui.bar(result.hero_equity, 20)))
        ui.para(comment, indent=6)
    print()
    ui.para("""
        Обратите внимание: даже пара тузов сохраняет часть equity —
        впереди четыре карты, и пара может «рассыпаться» в приличное
        лоу, если придут низкие карты. Но стартовать с неё всё равно
        не стоит: вы сразу позади.
    """)


def lesson_strategy() -> None:
    ui.title("Урок 3. Базовая стратегия для новичка")
    ui.para("""
        В раззе стратегия на удивление простая, потому что главный
        вопрос всегда один: насколько низкие у меня карты и насколько
        низкие видно у соперников.
    """)

    ui.section("С чем играть 3-ю улицу")
    ui.block("""
        Играем:    три карты от восьмёрки и ниже, без пар.
                   Чем младше — тем лучше. A-2-3 это мечта.
        Сбрасываем: любую пару;
                    любую руку, где есть карта старше восьмёрки
                    (кроме редких случаев с двумя очень низкими).
    """)
    print()

    ui.section("Что смотреть у соперников")
    ui.para("""
        Открытые карты соперников здесь работают в обе стороны.

        Если у соперников открыто много низких карт — ваше лоу
        становится лучше: низких карт в колоде осталось меньше,
        и соперникам будет труднее собрать хорошую руку. Но и вам
        тоже будет труднее.

        Если у соперников открыты короли и дамы — они, скорее всего,
        уже позади, и забрать банк проще.
    """)
    ui.hint("Разз — самая «честная» разновидность для изучения счёта "
            "мёртвых карт: здесь ровно видно, какие низкие карты уже "
            "ушли, и это напрямую превращается в решение.")

    ui.section("Частая ошибка")
    ui.para("""
        Не «цепляйтесь» за хороший старт после плохих улиц. Если
        у вас было A-2-3, а потом пришли король и дама — рука
        превратилась в мусор, сколько бы красивой она ни была
        изначально. Разз наказывает за упрямство быстрее других игр,
        потому что исправить руку заменой здесь нельзя.
    """)


