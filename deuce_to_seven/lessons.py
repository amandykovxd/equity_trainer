def lesson_rules() -> None:
    ui.title("Урок 1. Лоуболл, в котором стрит — это плохо")
    ui.para("""
        2-7 — это пятикарточный дро, в котором побеждает самая слабая
        рука. Но система оценки здесь совсем не та, что в раззе,
        и путать их нельзя.
    """)

    ui.section("Три правила системы 2-7")
    ui.block("""
        1. Туз — СТАРШАЯ карта. То есть для лоу он худший.
        2. Стриты и флеши считаются — и портят руку.
        3. Пары, тройки и каре, как и везде в лоу, тоже портят руку.
    """)
    print()
    ui.para("""
        Отсюда лучшая возможная рука: 7-5-4-3-2 разных мастей.
        Её называют «номер один».
    """)

    ui.section("Почему не 6-5-4-3-2 и не 7-6-5-4-3")
    hands = [
        ("7s5h4d3c2s", "лучшая возможная рука в 2-7"),
        ("6s5h4d3c2s", "ниже по картам — но это стрит, то есть плохо"),
        ("7s6h5d4c3s", "тоже стрит"),
        ("7s5h4d3c2h", "те же карты, но две червы — не флеш, всё в порядке"),
        ("7s5s4s3s2s", "а вот это флеш — рука испорчена"),
        ("As5h4d3c2s", "туз старший, поэтому это «туз-лоу» — плохая рука"),
        ("8s6h5d3c2s", "«восьмёрка-шесть» — нормальная рабочая рука"),
    ]
    print()
    for hand_text, comment in hands:
        hand = parse_cards(hand_text)
        print("  %s  %s" % (ui.pad(pretty(hand), 20),
                            describe_deuce_to_seven(hand)))
        ui.para(comment, indent=6)
    print()
    ui.hint("Проверяйте руку в таком порядке: нет ли пары, нет ли "
            "стрита, нет ли флеша — и только потом смотрите "
            "на старшую карту.")


def lesson_comparing() -> None:
    ui.title("Урок 2. Как сравнивают руки")
    ui.para("""
        Сравнение идёт со старшей карты, и чем она младше, тем лучше.
        При равной старшей карте смотрят следующую, и так далее.
    """)

    ui.section("Пример")
    first = parse_cards("8s6h4d3c2s")
    second = parse_cards("8s7h5d3c2s")
    print("  Рука 1: %s  →  %s" % (pretty(first),
                                   describe_deuce_to_seven(first)))
    print("  Рука 2: %s  →  %s" % (pretty(second),
                                   describe_deuce_to_seven(second)))
    print()
    ui.para("""
        У обеих старшая карта — восьмёрка. Дальше у первой шестёрка,
        у второй семёрка. Шестёрка младше, поэтому первая рука лучше.
        Говорят «восьмёрка-шесть бьёт восьмёрку-семь».
    """, indent=4)

    ui.section("Какие руки считаются сильными")
    ui.block("""
        7-5-4-3-2   «номер один» — сильнейшая рука
        7-6-4-3-2   вторая по силе
        8-x-x-x-x   рабочие руки, с ними обычно играют
        9-x-x-x-x   уже слабовато
        10 и старше почти всегда проигрыш
    """)
    print()
    ui.para("""
        Полезный ориентир: «восьмёрка» — это примерно как топ-пара
        в холдеме, а «семёрка» — почти нат.
    """)

    ui.section("Считаем equity")
    cases = [
        ("7s5h4d3c2s", "номер один — обыграть нельзя"),
        ("8d6h5c3d2c", "восьмёрка-шесть"),
        ("9s7c5d3h2s", "девятка-семь"),
        ("Js9h7d5c3s", "валет — рука для фолда"),
    ]
    villain = parse_cards("8s7h6d4c2h")
    print()
    print("  Против руки соперника %s (%s)"
          % (pretty(villain), describe_deuce_to_seven(villain)))
    print()
    for hand_text, comment in cases:
        hero = parse_cards(hand_text)
        result = equity(VARIANT, [hero, villain], seed=5)
        print("  %s  %5.1f%%  %s"
              % (ui.pad(pretty(hero), 20), result.hero_equity * 100,
                 ui.bar(result.hero_equity, 18)))
        ui.para(comment, indent=6)
    print()
    ui.para("""
        Обратите внимание: здесь обе руки готовы, карт впереди нет,
        поэтому equity равна либо 100%, либо 0% — вскрытие решает
        всё сразу. Так будет всегда, когда обе руки полные.
    """)


def lesson_drawing() -> None:
    ui.title("Урок 3. Замена и «пэт»")
    ui.para("""
        Версия, в которую играют чаще всего, называется трипл-дро:
        кругов замены три, а не один. Это значит, что плохую руку
        можно исправлять трижды — и соперник тоже.
    """)

    ui.section("Что меняют")
    ui.block("""
        Готовая рука (7 или 8 старшая)   не меняем — «стоим пэт»
        Четыре нужные карты              меняем одну
        Три нужные карты                 меняем две — уже рискованно
        Меньше трёх                      обычно сбрасываем
    """)
    print()
    ui.para("""
        Главная ошибка новичка — менять карты, держа «почти стрит».
        В 2-7 стрит это плохо, поэтому связанные карты здесь
        не ценность, а помеха: из 7-6-5-4 вам нужна не тройка
        и не восьмёрка, а двойка, и только она.
    """)

    ui.section("Информация из замены")
    ui.para("""
        Как и в обычном дро-покере, число заменённых карт говорит
        о руке:

          стоит пэт      →  заявляет готовую руку, обычно 8 или лучше;
          меняет одну    →  четыре карты есть, ждёт пятую;
          меняет две     →  рука пока слабая;
          меняет три     →  почти наверняка в плохом положении.

        В трипл-дро эта информация копится: игрок, который менял
        по одной карте три круга подряд, скорее всего так и не собрал.
    """)
    ui.hint("Стоять пэт с плохой рукой — классический блеф 2-7: "
            "соперник видит только то, что вы не меняли карт.")


