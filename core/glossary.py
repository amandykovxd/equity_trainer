TERMS: Dict[str, Term] = {}
for _term in TERM_LIST:
    if _term.key in TERMS:
        raise RuntimeError("Термин %s описан дважды" % _term.key)
    TERMS[_term.key] = _term


def by_group(group: str) -> List[Term]:
    return [term for term in TERM_LIST if term.group == group]


def for_variant(variant_key: str) -> List[Term]:
    """Термины, помеченные как важные именно для этой разновидности."""
    return [term for term in TERM_LIST if variant_key in term.variants]


def find(query: str) -> List[Term]:
    """Ищет термин по названию, ключу или синониму.

    Сначала пробует точное совпадение, потом вхождение подстроки —
    чтобы «аут» находил «Аутсы», а «equity» — и «Equity», и «Фолд-equity».
    """
    needle = query.strip().lower()
    if not needle:
        return []
    exact = [term for term in TERM_LIST if needle in term.search_keys]
    if exact:
        return exact
    partial = [term for term in TERM_LIST
               if any(needle in key for key in term.search_keys)]
    if partial:
        return partial
    # Последняя попытка: поискать в тексте определений.
    return [term for term in TERM_LIST
            if needle in term.definition.lower() or needle in term.detail.lower()]


def print_term(term: Term, show_group: bool = True) -> None:
    from . import ui

    print()
    print("  " + ui.color(term.name, ui.BOLD) +
          (ui.color("   [%s]" % term.group, ui.DIM) if show_group else ""))
    ui.para(term.definition, indent=4)
    if term.detail:
        print()
        ui.para(term.detail, indent=4)
    if term.aliases:
        print(ui.color("    также: %s" % ", ".join(term.aliases), ui.DIM))


def print_group(group: str) -> None:
    from . import ui

    ui.title("Словарь: %s" % group)
    for term in by_group(group):
        print_term(term, show_group=False)


def print_all() -> None:
    from . import ui

    ui.title("Словарь покерных терминов (%d штук)" % len(TERM_LIST))
    ui.para("""
        Термины сгруппированы по смыслу. Если вы начинаете с нуля,
        достаточно прочитать первые три группы — остальное будет
        попадаться по ходу уроков.
    """)
    for group in GROUPS:
        print_group(group)


def print_contents() -> None:
    """Короткий список групп с числом терминов."""
    from . import ui

    ui.title("Словарь покерных терминов")
    print()
    for group in GROUPS:
        terms = by_group(group)
        print("  %s%-26s%s %2d терминов" % (ui.BOLD, group, ui.RESET, len(terms)))
        names = ", ".join(term.name for term in terms)
        ui.para(names, indent=6)
        print()
    ui.hint("Показать группу целиком: python3 poker.py terms --group "
            "\"Математика\". Найти термин: python3 poker.py terms аутсы.")


def markdown() -> str:
    """Собирает GLOSSARY.md из этого же словаря."""
    lines = [
        "# Словарь покерных терминов",
        "",
        "%d термина, сгруппированных по смыслу. Этот файл собирается "
        "из `core/glossary.py`, поэтому он не может разойтись с тем, "
        "что показывает программа." % len(TERM_LIST),
        "",
        "Из терминала: `python3 poker.py terms <слово>`.",
        "",
        "## Содержание",
        "",
    ]
    for group in GROUPS:
        anchor = group.lower().replace(" ", "-")
        lines.append("- [%s](#%s) — %d" % (group, anchor, len(by_group(group))))
    lines.append("")
    for group in GROUPS:
        lines.append("## %s" % group)
        lines.append("")
        for term in by_group(group):
            lines.append("### %s" % term.name)
            lines.append("")
            lines.append(term.definition)
            lines.append("")
            if term.detail:
                lines.append(term.detail)
                lines.append("")
            if term.aliases:
                lines.append("*Также:* %s" % ", ".join(term.aliases))
                lines.append("")
    return "\n".join(lines)
