@dataclass(frozen=True)
class Term:
    key: str
    name: str
    group: str
    definition: str
    detail: str = ""
    aliases: Tuple[str, ...] = ()
    variants: Tuple[str, ...] = ()

    @property
    def search_keys(self) -> Tuple[str, ...]:
        return (self.key, self.name.lower()) + tuple(a.lower() for a in self.aliases)


def T(key: str, name: str, group: str, definition: str, detail: str = "",
      aliases: Sequence[str] = (), variants: Sequence[str] = ()) -> Term:
    return Term(key, name, group, definition, detail,
                tuple(aliases), tuple(variants))


