def lesson_rules() -> None:
    ui.title("Урок 1. Как идёт раздача в стаде")
    ui.para("""
        Стад — это покер до эпохи холдема, и устроен он иначе: общих
        карт здесь нет совсем. Каждый игрок собирает комбинацию только
        из своих семи карт, а часть этих карт открыта для всех.
    """)

    ui.section("Пять улиц и семь карт")
    ui.block("""
        3-я улица   две закрытые карты + одна открытая («дор-карта»)
        4-я улица   ещё одна открытая карта
        5-я улица   ещё одна открытая карта
        6-я улица   ещё одна открытая карта
        7-я улица   последняя карта, закрытая
    """)
    print()
    ui.para("""
        Итого у каждого 7 карт: 3 закрытые и 4 открытые. Комбинация —
        лучшие 5 из этих 7, порядок старшинства обычный (как в холдеме).
        Круг ставок идёт после каждой улицы.
    """)

    ui.section("Обязательные ставки")
    ui.para("""
        Вместо блайндов здесь анте: его платят все игроки до раздачи.
        Затем первым обязан поставить («бринг-ин») тот, у кого самая
        слабая открытая карта.

        Стад почти всегда играется с фиксированным лимитом: размер
        ставок задан правилами, произвольно повышать нельзя.
    """)

    ui.section("Пример готовой руки")
    hand = parse_cards("AsAhKd7c7h2s9d")
    print("  Ваши 7 карт: %s" % pretty(hand))
    print("  Комбинация:  %s%s%s" % (ui.BOLD, describe(hand), ui.RESET))
    ui.para("""
        В комбинацию вошли пять карт, две лишние просто не играют —
        как и в холдеме.
    """, indent=4)
    ui.hint("Главное, что нужно усвоить про стад: общих карт нет, "
            "поэтому «страшного борда» здесь не существует. Зато "
            "существует чужая открытая рука.")


def lesson_dead_cards() -> None:
    ui.title("Урок 2. Мёртвые карты — главный навык стада")
    ui.para("""
        Четыре из семи карт соперника вы видите своими глазами. Это
        значит, что вы знаете, каких карт в колоде уже нет, — и обязаны
        это учитывать. Карты, которые вы видели в чужих руках,
        называются мёртвыми.
    """)

    ui.section("Почему это важнее, чем кажется")
    hero = parse_cards("Ah9h2h")
    print("  У вас три червы: %s" % pretty(hero))
    ui.para("""
        В обычном расчёте у флеш-дро 10 аутсов: в масти 13 карт,
        три из них у вас. Но если за столом открыто лежат ещё четыре
        червы, аутсов остаётся шесть — почти вдвое меньше.

        Ваша equity при этом падает примерно во столько же раз,
        и колл, который был выгодным, становится убыточным. Никакая
        «правильная игра по учебнику» этого не компенсирует: нужно
        просто смотреть на стол.
    """)

    ui.section("Считаем разницу")
    from core.equity import exact_improve_chance

    print()
    for outs in (10, 8, 6, 4):
        chance = exact_improve_chance(outs, 40, 4)
        print("  аутсов %2d → собрать флеш к 7-й улице: %.0f%%  %s"
              % (outs, chance * 100, ui.bar(chance, 20)))
    print()
    ui.para("""
        Здесь посчитан шанс попасть хотя бы раз за четыре оставшиеся
        карты. Четыре мёртвых червы превращают хорошее дро
        в сомнительное.
    """)
    ui.hint("Привычка, которую стоит выработать с первой же раздачи: "
            "перед каждым решением глазами пробегать открытые карты "
            "соперников и искать среди них свои аутсы.")


def lesson_starting_hands() -> None:
    ui.title("Урок 3. С чем играть первые три карты")
    ui.para("""
        Решение в стаде принимается на 3-й улице, когда у вас три карты.
        Хороших стартов всего три типа.
    """)

    ui.section("Три типа играбельных рук")
    ui.block("""
        1. Тройка («свёрнутая тройка»)  777   — редкость и почти
                                               всегда победа
        2. Большая пара                 AA x  — особенно если пара
                                               закрыта
        3. Три карты одной масти        Ah9h2h — или три близкие карты
                                               на стрит
    """)
    print()
    ui.para("""
        Всё остальное на 3-й улице сбрасывается. Это не преувеличение:
        в стаде нет общих карт, а значит нет и дешёвых способов
        улучшиться — каждая улица стоит денег.
    """)

    ui.section("Сравним числами")
    cases = [
        ("7s7d7h", "Свёрнутая тройка семёрок"),
        ("AsAh4d", "Большая пара с лишней картой"),
        ("Ah9h2h", "Три червы — флеш-дро"),
        ("Kd8s3c", "Три несвязанные карты — типичный мусор"),
    ]
    villain = parse_cards("KsKh9d")
    print()
    print("  Против одной и той же руки соперника: %s" % pretty(villain))
    print("  (у обоих ещё по четыре карты впереди)")
    print()
    for hand_text, comment in cases:
        hero = parse_cards(hand_text)
        result = equity(VARIANT, [hero, villain], iterations=8000, seed=6)
        print("  %s  %5.1f%%  %s"
              % (ui.pad(pretty(hero), 14), result.hero_equity * 100,
                 ui.bar(result.hero_equity, 20)))
        ui.para(comment, indent=6)
    print()
    ui.hint("Обратите внимание на три червы: 36% против большой пары — "
            "это позиция догоняющего, а платить придётся на каждой "
            "из четырёх улиц по фиксированной ставке. А несвязанный "
            "мусор даёт всего 14%: именно поэтому на 3-й улице "
            "сбрасывают почти всё.")


