def lesson_rules() -> None:
    ui.title("Урок 1. Правила омахи и главное отличие от холдема")
    ui.para("""
        В омахе вам сдают четыре закрытые карты вместо двух. Общих карт,
        как и в холдеме, пять, и улицы те же: префлоп, флоп, тёрн, ривер.
    """)

    ui.section("Правило, на котором ошибаются все новички")
    ui.para("""
        Комбинация в омахе собирается из РОВНО двух ваших карт и РОВНО
        трёх общих. Не из одной, не из трёх, не из четырёх своих —
        всегда ровно из двух.
    """)
    hero = parse_cards("Ah2s3d4c")
    board = parse_cards("Kh7h2h")
    print()
    print("  Ваши карты: %s" % pretty(hero))
    print("  Борд:       %s" % pretty(board))
    print()
    ui.para("""
        На борде три червы, и у вас есть туз червей. В холдеме это было бы
        флеш-дро. В омахе — нет: чтобы собрать флеш, нужны ДВЕ червы
        на руках, а у вас одна. Второй червы взять неоткуда.
    """, indent=4)
    print()
    print("  Что у вас на самом деле: %s%s%s"
          % (ui.BOLD, VARIANT.describe(hero, board), ui.RESET))
    ui.hint("Привыкайте закрывать две свои карты рукой и смотреть, "
            "работает ли комбинация. Если нет — её нет.")

    ui.section("Как это выглядит, когда флеш настоящий")
    hero2 = parse_cards("AhKh2s3c")
    board2 = parse_cards("Qh7h5h")
    print("  Ваши карты: %s" % pretty(hero2))
    print("  Борд:       %s" % pretty(board2))
    print("  Комбинация: %s%s%s"
          % (ui.BOLD, VARIANT.describe(hero2, board2), ui.RESET))
    ui.para("""
        Здесь две червы на руках и три на борде — ровно два плюс ровно
        три. Флеш есть, и это нат: старше туза червей не бывает.
    """, indent=4)

    ui.section("Шесть рук в одной")
    ui.para("""
        Четыре карты дают шесть разных пар, и каждая пара — это
        фактически отдельная рука холдема:
    """)
    hand = parse_cards("AhKh7s8s")
    print()
    for two in combinations(hand, 2):
        print("      %s" % pretty(two))
    print()
    ui.para("""
        Отсюда главное следствие: в омахе почти у каждого что-то есть.
        Руки, которые в холдеме считались бы сильными, здесь часто
        оказываются второй или третьей по силе.
    """)


def lesson_strength() -> None:
    ui.title("Урок 2. Почему в омахе всё иначе по силе рук")
    ui.para("""
        Посчитаем то же самое, что в холдеме, и сравним числа —
        они говорят лучше любых объяснений.
    """)

    ui.section("Тузы в омахе стоят дешевле, чем в холдеме")
    cases = [
        ("AsAh2d7c", "KsKd3h8c", "Тузы против королей (обе руки «слабые»)"),
        ("AsAhKsKh", "9s8d7h6c", "Тузы с королями, двойная масть, против "
                                 "связки средних карт"),
        ("AsAh2d7c", None, "Тузы с мусором против одной случайной руки"),
        ("AsAhKsKh", None, "Тузы с королями и двойной мастью против "
                           "случайной руки"),
    ]
    print()
    for hero_text, villain_text, comment in cases:
        hero = parse_cards(hero_text)
        if villain_text:
            result = equity(VARIANT, [hero, parse_cards(villain_text)], seed=5)
            against = pretty(parse_cards(villain_text))
        else:
            result = equity(VARIANT, [hero, []], seed=5)
            against = "случайной руки"
        print("  %s  против %s  %5.1f%%  %s"
              % (pretty(hero), ui.pad(against, 20), result.hero_equity * 100,
                 ui.bar(result.hero_equity, 18)))
        ui.para(comment, indent=6)
    print()
    ui.para("""
        В холдеме тузы против случайной руки дают около 85%. В омахе
        даже лучшая стартовая рука не дотягивает до 75%, а голые тузы
        с мусором — и вовсе едва выше 60%.

        Причина простая: у соперника четыре карты, то есть шесть
        возможных пар. Шансов попасть во что-нибудь у него намного больше.
    """)
    ui.hint("Вывод для новичка: в омахе нельзя выигрывать за счёт одной "
            "сильной пары. Здесь выигрывают наты и дро, которые идут "
            "к натам.")


def lesson_draws() -> None:
    ui.title("Урок 3. Дро в омахе: когда аутсов двадцать")
    ui.para("""
        В холдеме максимум, который обычно встречается, — это 15 аутсов.
        В омахе четыре карты работают одновременно, и дро бывают такими,
        каких в холдеме не существует.
    """)

    ui.section("Рэп — стрит-дро из нескольких карт сразу")
    hero = parse_cards("Qd9h8s7c")
    villain = parse_cards("AsAd2c3d")
    board = parse_cards("JhTc5s")
    print("  Ваши карты:      %s" % pretty(hero))
    print("  Борд:            %s" % pretty(board))
    print("  Карты соперника: %s  (%s)"
          % (pretty(villain), VARIANT.describe(villain, board)))
    print("  У вас сейчас:    %s" % VARIANT.describe(hero, board))
    print()
    outs, _ties = next_card_outs(VARIANT, hero, villain, board)
    print("  Аутсов: %d" % len(outs))
    print("  Это карты: %s"
          % pretty(sorted(outs, key=lambda c: (-c.rank, c.suit))))
    ui.para("""
        Считаем, откуда их столько. На борде J и T, они попадают
        в пять подряд идущих карт вместе с вашими. Стрит собирают
        семёрка, восьмёрка, девятка, дама и король — пять разных
        номиналов. Три из них частично у вас на руках, поэтому
        не двадцать карт, а шестнадцать.
    """, indent=4)
    print()
    result = equity(VARIANT, [hero, villain], board, seed=3)
    print("  Ваша equity: %.1f%%  %s"
          % (result.hero_equity * 100, ui.bar(result.hero_equity, 22)))
    ui.para("""
        У вас нет ни пары, ни флеш-дро — и при этом вы уверенный фаворит
        против карманных тузов. Такое стрит-дро называется «рэп»:
        несколько ваших карт работают на стрит одновременно. В холдеме
        такой руки не бывает в принципе: там на стрит работают максимум
        две карты.
    """)

    ui.section("Что из этого следует")
    ui.para("""
        В омахе дро часто сильнее готовой руки. Поэтому здесь нормально
        ставить с недособранной рукой и нормально сбрасывать пару
        на опасном борде.

        И обратное: если у вас готовая, но не натовая рука, а соперник
        ставит много, вы, скорее всего, уже вторые.
    """)
    ui.hint("Главное слово в омахе — «нат». Перед каждым крупным "
            "решением спрашивайте себя: какая рука здесь сильнейшая "
            "и есть ли она у меня.")


def lesson_starting_hands() -> None:
    ui.title("Урок 4. Стартовые руки в омахе")
    ui.para("""
        В омахе 16 432 принципиально разных стартовых руки, так что
        таблицу, как в холдеме, выучить невозможно. Вместо таблицы —
        четыре признака хорошей руки.
    """)

    ui.section("Признаки хорошей руки")
    ui.block("""
        1. Карты работают вместе      AsKs9h8h  — лучше, чем As9h2c7d
        2. Двойная масть              две разные масти по две карты
        3. Связность                  близкие номиналы: 9-8-7-6
        4. Старшие карты              A-K-Q-J сильнее 8-7-6-5
    """)
    print()
    ui.para("""
        Самое важное — первый пункт. Четыре не связанные между собой
        карты это, по сути, одна-две руки холдема вместо шести,
        то есть выброшенные деньги.
    """)

    ui.section("Сравним руки числами")
    hands = [
        ("AsAhKsKh", "Тузы с королями, двойная масть — лучшая рука омахи"),
        ("Js Ts 9h 8h", "Связка средних карт с двойной мастью"),
        ("AsKsQhJh", "Четыре старшие карты, двойная масть"),
        ("As2s7d8c", "Туз с мусором — типичная ловушка новичка"),
        ("As Ah 2c 7d", "Тузы без поддержки: шесть пар, но работают две"),
    ]
    print()
    for hand_text, comment in hands:
        hero = parse_cards(hand_text)
        result = equity(VARIANT, [hero, []], iterations=4000, seed=11)
        print("  %s  %5.1f%%  %s"
              % (ui.pad(pretty(hero), 22), result.hero_equity * 100,
                 ui.bar(result.hero_equity, 18)))
        ui.para(comment, indent=6)
    print()
    ui.para("""
        Разница между лучшей и худшей рукой здесь гораздо меньше, чем
        в холдеме (там это 85% против 35%). Именно поэтому в омахе
        преимущество набирается не стартовыми картами, а умением
        играть после флопа.
    """)
    ui.hint("Пока вы новичок: играйте руки, где все четыре карты связаны "
            "хотя бы попарно, и сбрасывайте всё, где есть «лишняя» карта "
            "вроде двойки или семёрки без масти.")


